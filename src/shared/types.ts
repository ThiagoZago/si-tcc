export type AppointmentStatus = "pending" | "confirmed" | "completed" | "cancelled" | "no_show";
export type DayHours = {
  active: boolean;
  start: string;
  end: string;
  breakStart: string;
  breakEnd: string;
};
export type Availability = DayHours[];
export type User = { id: string; name: string; email: string; createdAt: string };
export type Business = {
  id: string;
  ownerId: string;
  name: string;
  slug: string;
  description: string;
  phone: string;
  email: string;
  address: string;
  city: string;
  hours: Availability;
  createdAt: string;
};
export type Service = {
  id: string;
  businessId: string;
  name: string;
  description: string;
  price: number;
  duration: number;
  active: boolean;
  professionalIds: string[];
};
export type Professional = {
  id: string;
  businessId: string;
  name: string;
  role: string;
  bio: string;
  color: string;
  active: boolean;
  availability: Availability;
  exceptions: string[];
};
export type Customer = {
  id: string;
  businessId: string;
  name: string;
  phone: string;
  email: string;
  notes: string;
  createdAt: string;
  visits?: number;
  totalSpent?: number;
  lastVisit?: string | null;
};
export type Appointment = {
  id: string;
  businessId: string;
  customerId: string;
  professionalId: string;
  serviceId: string;
  date: string;
  time: string;
  startMinutes: number;
  duration: number;
  price: number;
  status: AppointmentStatus;
  notes: string;
  customerName: string;
  customerPhone: string;
  serviceName: string;
  professionalName: string;
  professionalColor: string;
  createdAt: string;
};
export type WaitlistEntry = {
  id: string;
  businessId: string;
  customerName: string;
  phone: string;
  date: string;
  serviceId: string;
  serviceName: string;
  professionalId: string;
  professionalName: string;
  status: "waiting" | "contacted" | "closed";
  createdAt: string;
};
export type Catalog = { business: Business; services: Service[]; professionals: Professional[] };
export type DashboardData = {
  user: User;
  business: Business;
  appointments: Appointment[];
  services: Service[];
  professionals: Professional[];
  customers: Customer[];
  waitlist: WaitlistEntry[];
};
